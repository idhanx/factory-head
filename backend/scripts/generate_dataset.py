"""Generate the full-product FactoryManager AI test dataset.

    python scripts/generate_dataset.py                       # everything, default paths
    python scripts/generate_dataset.py --formats sql,csv     # skip Excel
    python scripts/generate_dataset.py --out /tmp/fm-data

Output (default ``../datasets/factorymanager_dataset``):

    sql/factorymanager_data.sql     INSERTs for every table, FK-ordered, one transaction
    sql/00_reset_all_tables.sql     optional TRUNCATE (destructive — read before running)
    csv/<table>.csv + load_csv.sql  one CSV per table and a psql \\copy loader
    excel/factorymanager_dataset.xlsx   every table as a sheet, with a README sheet
    forms/<PLANT>/T1..T7_*.xlsx     filled onboarding templates, parser-verified
    forms/Readiness_Questionnaire_Responses.xlsx
    manifest.json                   row counts, seed, as-of date
    README.md                       what is in it and how to load it

The data is generated by ``scripts/dataset`` through ``app.kernel``; see that
package's docstrings for how each table is produced.
"""

from __future__ import annotations

import argparse
import json
import sys
import time as clock
from datetime import UTC, date, datetime, time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from scripts.dataset import export
from scripts.dataset.catalog import PLANTS
from scripts.dataset.readme import render_readme
from scripts.dataset.simulate import IST, Generator

DEFAULT_OUT = Path(__file__).resolve().parents[2] / "datasets" / "factorymanager_dataset"


def alembic_head() -> tuple[str, str]:
    """The current migration head and its message, read from the migrations.

    Hardcoding the revision is how the last one went stale: the dataset said
    ``0ba4b6bb4343`` long after five more migrations had landed, so anyone
    following the README loaded it into a schema it no longer matched.
    """
    from alembic.config import Config
    from alembic.script import ScriptDirectory

    root = Path(__file__).resolve().parents[1]
    script = ScriptDirectory.from_config(Config(str(root / "alembic.ini")))
    head = script.get_current_head()
    revision = script.get_revision(head)
    return head, (revision.doc or "").strip()


def main() -> None:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    parser.add_argument("--seed", type=int, default=20260913)
    parser.add_argument(
        "--as-of",
        type=date.fromisoformat,
        default=date(2026, 9, 12),
        help="last business day in the data",
    )
    parser.add_argument(
        "--now",
        default="11:20",
        help="time of day on --as-of when the data 'stops' (HH:MM IST)",
    )
    parser.add_argument("--formats", default="sql,csv,xlsx,forms")
    args = parser.parse_args()

    head, head_note = alembic_head()
    formats = {f.strip() for f in args.formats.split(",") if f.strip()}
    now = datetime.combine(args.as_of, time.fromisoformat(args.now), tzinfo=IST)
    started = clock.perf_counter()

    print(
        f"Simulating {len(PLANTS)} plants up to {now:%Y-%m-%d %H:%M} IST (seed {args.seed})..."
    )
    generator = Generator(seed=args.seed, as_of=args.as_of, now=now, plants=PLANTS)
    store = generator.run()
    counts = store.counts()
    total = sum(counts.values())
    print(
        f"  {total:,} rows across {sum(1 for c in counts.values() if c)} tables ({clock.perf_counter() - started:.1f}s)"
    )

    out: Path = args.out
    out.mkdir(parents=True, exist_ok=True)
    manifest = {
        "product": "FactoryManager AI",
        "schema_revision": f"{head} ({head_note})" if head_note else head,
        "seed": args.seed,
        "as_of": args.as_of.isoformat(),
        "data_stops_at": now.isoformat(),
        "generated_at": datetime.now(UTC).isoformat(timespec="seconds"),
        "timezone_note": "All timestamps are Asia/Kolkata (+05:30). Money columns are integer paise (100 paise = ₹1).",
        "total_rows": total,
        "tables": counts,
        "plants": [
            {
                "code": s.code,
                "name": s.name,
                "location": s.location,
                "costing_mode": s.costing_mode,
                "go_live": s.go_live.isoformat(),
                "lot_granularity": s.lot_granularity,
                "shifts": [sh.name for sh in s.shifts],
            }
            for s in PLANTS
        ],
    }

    header = (
        "-- FactoryManager AI — full-product test dataset\n"
        f"-- {total:,} rows, {len(PLANTS)} plants, data up to {now.isoformat()}\n"
        f"-- Load into an EMPTY schema at Alembic head ({head}):\n"
        "--   cd backend && alembic upgrade head\n"
        '--   psql "$DATABASE_URL" -v ON_ERROR_STOP=1 -f factorymanager_data.sql\n'
        "-- Money is integer paise. Timestamps are IST (+05:30).\n"
    )

    if "sql" in formats:
        (out / "sql").mkdir(exist_ok=True)
        parts = export.write_sql(store, out / "sql" / "factorymanager_data.sql", header)
        export.write_reset_sql(store, out / "sql" / "00_reset_all_tables.sql")
        manifest["sql_parts"] = parts
        print(f"  sql ............ done ({len(parts)} part files)")
    if "csv" in formats:
        files = export.write_csv(store, out / "csv")
        manifest["csv_files"] = {k: v for k, v in files.items() if len(v) > 1}
        split = sum(len(v) for v in files.values() if len(v) > 1)
        print(f"  csv ............ done{f' ({split} part files for large tables)' if split else ''}")
    if "xlsx" in formats:
        (out / "excel").mkdir(exist_ok=True)
        summary = [
            ["FactoryManager AI — full-product test dataset"],
            [
                f"{total:,} rows · {len(PLANTS)} plants · data up to {now:%Y-%m-%d %H:%M} IST"
            ],
            [
                "Money columns are integer paise (divide by 100 for ₹). Timestamps are IST; JSON columns are shown as text."
            ],
        ]
        export.write_excel(store, out / "excel" / "factorymanager_dataset.xlsx", summary)
        print("  xlsx ........... done")
    forms_report = {}
    if "forms" in formats:
        forms_report = export.write_forms(generator.forms, store, out / "forms")
        manifest["onboarding_forms"] = forms_report
        print("  forms .......... done (all T1-T7 parse cleanly)")

    manifest["demo_logins"] = generator.credentials
    (out / "manifest.json").write_text(
        json.dumps(manifest, indent=2, ensure_ascii=False), encoding="utf-8"
    )
    (out / "README.md").write_text(render_readme(manifest, generator), encoding="utf-8")

    print("\nRows per table:")
    for name, count in counts.items():
        print(f"  {name:<28} {count:>8,}")
    print(f"  {'TOTAL':<28} {total:>8,}")
    print(f"\nWritten to {out} in {clock.perf_counter() - started:.1f}s")


if __name__ == "__main__":
    main()
