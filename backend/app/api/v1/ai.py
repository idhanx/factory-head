"""Layer 2's Coach and Layer 3's Copilot."""

from __future__ import annotations

from datetime import date

from fastapi import APIRouter, Depends, HTTPException, status
from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from app.ai import coach as coach_service
from app.ai import copilot as copilot_service
from app.api.deps import Identity, get_identity, get_plant, get_session, require
from app.kernel import format_inr
from app.models import CoachBriefing, Plant, Role
from app.schemas import (
    CoachBriefingOut,
    CoachPriorityOut,
    CopilotRequest,
    CopilotResponse,
)
from app.services.clock import plant_today

router = APIRouter(prefix="/ai", tags=["ai"])

TIER_LABELS = {
    0: "Silent — not enough history to coach yet",
    1: "Rule-based — biggest losses and overdue actions",
    2: "Pattern — recurrence intervals and risk windows",
    3: "Deep — day-of-week effects and correlations",
}


@router.get("/coach/today", response_model=CoachBriefingOut)
async def coach_today(
    business_date: date | None = None,
    identity: Identity = Depends(get_identity),
    plant: Plant = Depends(get_plant),
    session: AsyncSession = Depends(get_session),
):
    """The 5:45 AM briefing. Exactly three priorities, or an honest silence.

    Generated by the worker before the shift. A read returns what is stored and
    never generates one: a page view must not write a briefing, and a briefing
    that appears the first time someone looks cannot claim it was sent at 5:45.
    """
    business_date = business_date or plant_today(plant)

    briefing = await session.scalar(
        select(CoachBriefing)
        .where(
            CoachBriefing.plant_id == plant.id,
            CoachBriefing.business_date == business_date,
        )
        .order_by(CoachBriefing.created_at.desc())
        .limit(1)
    )
    if briefing is None:
        raise HTTPException(status.HTTP_404_NOT_FOUND, "No briefing yet")

    return _briefing_out(briefing)


@router.post(
    "/coach/generate",
    response_model=CoachBriefingOut,
    dependencies=[Depends(require(Role.SUPERVISOR, Role.OWNER, Role.CONSULTANT))],
)
async def generate(
    business_date: date | None = None,
    identity: Identity = Depends(get_identity),
    plant: Plant = Depends(get_plant),
    session: AsyncSession = Depends(get_session),
):
    briefing = await coach_service.generate_briefing(
        session,
        plant=plant,
        recipient_id=identity.user.id,
        as_of=business_date or plant_today(plant),
    )
    return _briefing_out(briefing)


@router.post("/copilot/ask", response_model=CopilotResponse)
async def ask(
    payload: CopilotRequest,
    identity: Identity = Depends(get_identity),
    plant: Plant = Depends(get_plant),
    session: AsyncSession = Depends(get_session),
):
    """Ask anything, in English or Tamil, and get an answer from your own data.

    Factual questions work from day one. Pattern questions are withheld until
    enough events exist to support them — and the refusal is explicit, because
    "I've seen 2 events like this; I'll give you pattern analysis once I've seen
    more" keeps trust, while a confident guess destroys it.
    """
    answer = await copilot_service.ask(
        session,
        plant=plant,
        question=payload.question,
        user_id=identity.user.id,
        language=payload.language,
        channel="web",
        as_of=plant_today(plant),
    )
    return CopilotResponse(
        answer=answer.answer,
        intent=answer.intent,
        tier_available=answer.tier_available,
        facts=answer.facts,
        evidence=answer.evidence,
        answered_by=answer.answered_by,
        latency_ms=answer.latency_ms,
    )


def _briefing_out(briefing: CoachBriefing) -> CoachBriefingOut:
    return CoachBriefingOut(
        id=briefing.id,
        business_date=briefing.business_date,
        tier=briefing.tier,
        tier_label=TIER_LABELS.get(briefing.tier, ""),
        priorities=[
            CoachPriorityOut(**{**p, "value_display": format_inr(p.get("value_paise", 0))})
            for p in (briefing.priorities or [])
        ],
        rendered_text=briefing.rendered_text,
        generated_by=briefing.generated_by,
        data_basis=briefing.data_basis,
    )
